	@Override
	public boolean doHurtTarget(ServerLevel level, Entity target) {
		boolean hit = super.doHurtTarget(level, target);
		if (hit && target instanceof LivingEntity living) {
			Vec3 push = living.position().subtract(position()).multiply(1, 0, 1).normalize().scale(1.1);
			living.push(push.x, 0.4, push.z);
			living.hurtMarked = true;
			BuiltInRegistries.MOB_EFFECT.getOptional(ResourceLocation.parse("minecraft:weakness")).map(BuiltInRegistries.MOB_EFFECT::wrapAsHolder)
					.ifPresent(holder -> living.addEffect(new MobEffectInstance(holder, 160, 0)));
		}
		return hit;
	}

